import 'dart:convert';

import 'amount.dart';
import 'issues.dart';
import 'vpa.dart';

/// Where to open a payment link.
///
/// Android shows the payer a chooser for plain `upi://pay` links. iOS has no
/// chooser, so you open a specific app with its own URL scheme. Add the
/// schemes you use to `LSApplicationQueriesSchemes` in `Info.plist`.
enum UpiApp {
  /// Any UPI app (`upi://pay`). The right choice on Android.
  any('upi://pay'),
  googlePay('gpay://upi/pay'),
  phonePe('phonepe://pay'),
  paytm('paytmmp://pay');

  const UpiApp(this.prefix);

  /// Everything before the `?`.
  final String prefix;
}

/// A UPI payment link: the `upi://pay?pa=…&pn=…&am=…` string inside UPI QR
/// codes and payment intents.
///
/// Build one and call [toString] to get the link, or [parse] a link you
/// scanned. [validate] tells you what payment apps would reject.
///
/// Parameter names follow NPCI's UPI linking specification.
final class UpiPaymentLink {
  const UpiPaymentLink({
    required this.payeeVpa,
    this.payeeName,
    this.amount,
    this.minimumAmount,
    this.note,
    this.transactionRef,
    this.transactionId,
    this.merchantCategoryCode,
    this.currency = 'INR',
    this.url,
    this.mode,
    this.purpose,
    this.extra = const {},
  });

  /// `pa`: the UPI ID being paid, such as `sharmastores@okicici`.
  final String payeeVpa;

  /// `pn`: the name the payer sees.
  final String? payeeName;

  /// `am`: a fixed amount. Leave it null to let the payer type one.
  final UpiAmount? amount;

  /// `mam`: the least the payer may enter.
  final UpiAmount? minimumAmount;

  /// `tn`: a note shown to the payer and in both parties' statements.
  final String? note;

  /// `tr`: your own reference, such as an order or invoice number.
  final String? transactionRef;

  /// `tid`: a transaction ID generated by the payee's payment provider.
  final String? transactionId;

  /// `mc`: the four-digit merchant category code.
  final String? merchantCategoryCode;

  /// `cu`: always `INR` for UPI.
  final String currency;

  /// `url`: a link with more details about the payment.
  final String? url;

  /// `mode`: how the payment was started (for example from a QR code).
  final String? mode;

  /// `purpose`: the purpose code.
  final String? purpose;

  /// Any other parameters, kept in order. Parsing puts unknown ones here so
  /// that nothing is lost.
  final Map<String, String> extra;

  /// Parses a `upi://pay` link.
  ///
  /// Accepts upper-case links (common in QR codes), a trailing slash and
  /// parameter names in any case. Throws a [FormatException] if [input] isn't
  /// a `upi://pay` link, has no `pa`, or has an amount that isn't one.
  static UpiPaymentLink parse(String input) {
    final text = input.trim();
    final query = _queryOf(text);
    if (query == null) {
      throw FormatException('Not a upi://pay link', input);
    }

    final params = <String, String>{};
    for (final pair in query.split('&')) {
      if (pair.isEmpty) continue;
      final eq = pair.indexOf('=');
      final key = (eq < 0 ? pair : pair.substring(0, eq)).toLowerCase();
      final value = eq < 0 ? '' : _decode(pair.substring(eq + 1));
      params.putIfAbsent(key, () => value);
    }

    final pa = params.remove('pa');
    if (pa == null || pa.isEmpty) {
      throw FormatException('The link has no payee UPI ID (pa)', input);
    }

    UpiAmount? amountParam(String key) {
      final value = params.remove(key);
      if (value == null || value.isEmpty) return null;
      final amount = UpiAmount.tryParse(value);
      if (amount == null) {
        throw FormatException('"$key" is not an amount: "$value"', input);
      }
      return amount;
    }

    String? take(String key) {
      final value = params.remove(key);
      return value == null || value.isEmpty ? null : value;
    }

    return UpiPaymentLink(
      payeeVpa: pa,
      payeeName: take('pn'),
      amount: amountParam('am'),
      minimumAmount: amountParam('mam'),
      note: take('tn'),
      transactionRef: take('tr'),
      transactionId: take('tid'),
      merchantCategoryCode: take('mc'),
      currency: take('cu') ?? 'INR',
      url: take('url'),
      mode: take('mode'),
      purpose: take('purpose'),
      extra: Map.unmodifiable(params),
    );
  }

  /// Like [parse], but returns null instead of throwing.
  static UpiPaymentLink? tryParse(String input) {
    try {
      return parse(input);
    } on FormatException {
      return null;
    }
  }

  /// Whether [input] looks like a `upi://pay` link, without parsing it.
  static bool looksLikeLink(String input) => _queryOf(input.trim()) != null;

  static String? _queryOf(String text) {
    final lower = text.toLowerCase();
    for (final prefix in const ['upi://pay?', 'upi://pay/?']) {
      if (lower.startsWith(prefix)) return text.substring(prefix.length);
    }
    return null;
  }

  /// The parameters in the order payment apps expect, without empty ones.
  Map<String, String> get parameters => {
        'pa': payeeVpa,
        if (payeeName != null) 'pn': payeeName!,
        if (merchantCategoryCode != null) 'mc': merchantCategoryCode!,
        if (transactionId != null) 'tid': transactionId!,
        if (transactionRef != null) 'tr': transactionRef!,
        if (note != null) 'tn': note!,
        if (amount != null) 'am': amount!.format(),
        if (minimumAmount != null) 'mam': minimumAmount!.format(),
        'cu': currency,
        if (url != null) 'url': url!,
        if (mode != null) 'mode': mode!,
        if (purpose != null) 'purpose': purpose!,
        ...extra,
      };

  /// The link to open with [app], for example with `url_launcher`.
  ///
  /// Spaces are encoded as `%20`, not `+`, because some payment apps show a
  /// literal `+`.
  String toLink([UpiApp app = UpiApp.any]) {
    final query =
        parameters.entries.map((e) => '${e.key}=${_encode(e.value)}').join('&');
    return '${app.prefix}?$query';
  }

  /// [toLink] as a [Uri].
  Uri toUri([UpiApp app = UpiApp.any]) => Uri.parse(toLink(app));

  /// Checks the link against the rules payment apps apply.
  ///
  /// Returns an empty list when nothing is wrong. Issues with
  /// [UpiIssueSeverity.error] mean apps will refuse the payment.
  List<UpiIssue> validate() {
    final issues = <UpiIssue>[];
    if (!Vpa.isValid(payeeVpa)) {
      issues.add(UpiIssue(UpiIssueCode.invalidVpa, 'pa',
          '"$payeeVpa" is not a valid UPI ID (expected name@handle)'));
    }
    if (payeeName == null || payeeName!.trim().isEmpty) {
      issues.add(const UpiIssue(UpiIssueCode.missingPayeeName, 'pn',
          'No payee name: many apps warn the payer or refuse the payment',
          severity: UpiIssueSeverity.warning));
    }
    if (amount != null && amount!.isZero) {
      issues.add(const UpiIssue(
          UpiIssueCode.zeroAmount, 'am', 'The amount must be more than zero'));
    }
    if (amount != null && minimumAmount != null && minimumAmount! > amount!) {
      issues.add(UpiIssue(UpiIssueCode.minimumAboveAmount, 'mam',
          'The minimum amount ($minimumAmount) is more than the amount ($amount)'));
    }
    if (merchantCategoryCode != null &&
        !RegExp(r'^\d{4}$').hasMatch(merchantCategoryCode!)) {
      issues.add(UpiIssue(UpiIssueCode.invalidMerchantCategoryCode, 'mc',
          'The merchant category code must be four digits'));
    }
    if (currency.toUpperCase() != 'INR') {
      issues.add(UpiIssue(UpiIssueCode.unsupportedCurrency, 'cu',
          'UPI only supports INR, not "$currency"'));
    }
    if (transactionRef != null && transactionRef!.length > 35) {
      issues.add(const UpiIssue(
          UpiIssueCode.transactionRefLength,
          'tr',
          'The transaction reference is longer than 35 characters, '
              'which some apps cut off or reject',
          severity: UpiIssueSeverity.warning));
    }
    if (url != null) {
      final uri = Uri.tryParse(url!);
      if (uri == null || !(uri.isScheme('http') || uri.isScheme('https'))) {
        issues.add(const UpiIssue(UpiIssueCode.invalidUrl, 'url',
            'The reference URL must start with http:// or https://'));
      }
    }
    return issues;
  }

  /// Whether [validate] finds no errors (warnings are allowed).
  bool get isValid => !validate().any((issue) => issue.isError);

  UpiPaymentLink copyWith({
    String? payeeVpa,
    String? payeeName,
    UpiAmount? amount,
    UpiAmount? minimumAmount,
    String? note,
    String? transactionRef,
    String? transactionId,
    String? merchantCategoryCode,
    String? currency,
    String? url,
    String? mode,
    String? purpose,
    Map<String, String>? extra,
  }) =>
      UpiPaymentLink(
        payeeVpa: payeeVpa ?? this.payeeVpa,
        payeeName: payeeName ?? this.payeeName,
        amount: amount ?? this.amount,
        minimumAmount: minimumAmount ?? this.minimumAmount,
        note: note ?? this.note,
        transactionRef: transactionRef ?? this.transactionRef,
        transactionId: transactionId ?? this.transactionId,
        merchantCategoryCode: merchantCategoryCode ?? this.merchantCategoryCode,
        currency: currency ?? this.currency,
        url: url ?? this.url,
        mode: mode ?? this.mode,
        purpose: purpose ?? this.purpose,
        extra: extra ?? this.extra,
      );

  @override
  bool operator ==(Object other) =>
      other is UpiPaymentLink && other.toLink() == toLink();

  @override
  int get hashCode => toLink().hashCode;

  @override
  String toString() => toLink();
}

bool _isUnreserved(int c) =>
    (c >= 0x30 && c <= 0x39) || // 0-9
    (c >= 0x41 && c <= 0x5A) || // A-Z
    (c >= 0x61 && c <= 0x7A) || // a-z
    c == 0x2D || // -
    c == 0x2E || // .
    c == 0x5F || // _
    c == 0x7E || // ~
    c == 0x40; // @, kept readable in UPI IDs

String _encode(String value) {
  final out = StringBuffer();
  for (final byte in utf8.encode(value)) {
    if (_isUnreserved(byte)) {
      out.writeCharCode(byte);
    } else {
      out.write('%${byte.toRadixString(16).toUpperCase().padLeft(2, '0')}');
    }
  }
  return out.toString();
}

String _decode(String value) {
  try {
    return Uri.decodeQueryComponent(value);
  } on ArgumentError {
    // A stray `%` that isn't an escape: keep the text as it was written.
    return value;
  } on FormatException {
    return value;
  }
}
